"""Worker-callable orchestration. P2 owns claiming jobs; P1/P4 own learning content."""

import asyncio
import logging
import traceback
from collections.abc import Awaitable, Callable, Sequence
from dataclasses import dataclass, replace
from datetime import UTC, datetime
from typing import Literal, Protocol

from pydantic import BaseModel, ConfigDict, Field, JsonValue, ValidationError

from app.api.topics import TopicInput
from app.graders.mcq import Item
from app.research.agent import ChosenSource, OnEvent, research
from app.research.reader import SourceError
from app.schemas import Citation, KnowledgeGraph
from app.schemas import Item as ContractItem
from app.uploads.reader import Document

logger = logging.getLogger(__name__)


class PreparedChunk(BaseModel):
    model_config = ConfigDict(extra="forbid")
    id: str = Field(min_length=1)
    text: str = Field(min_length=1)
    source_uri: str = Field(min_length=1)
    page: int | None = Field(default=None, ge=1)
    source_url: str | None = None  # registered book URL; source_uri remains the exact page


class GraphDraft(BaseModel):
    model_config = ConfigDict(extra="forbid")
    subject_slug: str = Field(min_length=1)
    graph: dict[str, JsonValue]
    # P4's validation outcome, not an LLM-generated trust flag.
    supported: bool


@dataclass(frozen=True)
class SourceSummary:
    title: str
    publisher: str
    url: str
    license: str


@dataclass(frozen=True)
class Progress:
    status: Literal["researching", "indexing", "graph", "items", "ready", "failed"]
    step_vi: str
    progress: int
    graph_ready: bool = False
    items_ready: bool = False
    subject_slug: str | None = None
    dropped_items: int = 0
    sources: tuple[SourceSummary, ...] = ()


@dataclass(frozen=True)
class PipelineResult:
    subject_slug: str
    item_ids: tuple[str, ...]
    sources: tuple[ChosenSource, ...]
    dropped_items: int


class PipelinePorts(Protocol):
    """P3's adapter ports; implementations translate existing P1/P2/P4 signatures.

    index returns persistent real chunk IDs/provenance; graph/items call P4 and its
    cross-family verification gate. save_graph/save_items must be retry-safe upserts.
    No fake graph, chunks or verified labels are generated by this orchestration.
    """

    async def load_upload(self, upload_id: str) -> Document | None: ...
    async def quick_sources(self, goal: str) -> Sequence[ChosenSource]: ...
    async def index(
        self,
        sources: Sequence[ChosenSource],
        upload: Document | None,
    ) -> Sequence[PreparedChunk]: ...
    async def build_graph(
        self,
        goal: str,
        chunks: Sequence[PreparedChunk],
        tier: str,
    ) -> GraphDraft: ...
    async def save_graph(self, graph: GraphDraft) -> None: ...
    async def build_items(
        self,
        graph: GraphDraft,
        chunks: Sequence[PreparedChunk],
        tier: str,
        count: int,
    ) -> Sequence[Item]: ...
    async def save_items(self, subject_slug: str, items: Sequence[Item]) -> None: ...


Research = Callable[[str, OnEvent], Awaitable[list[ChosenSource]]]
OnProgress = Callable[[Progress], Awaitable[None]]


class ChunkRetriever(Protocol):
    async def search(self, query: str, subject: str, k: int = 5) -> list[Citation]: ...


async def retrieve_chunks(
    retriever: ChunkRetriever,
    goal: str,
    subject: str,
    chunks: Sequence[PreparedChunk],
    k: int,
) -> list[PreparedChunk]:
    """Check durable citation identity, then restore prepared document reading order."""
    citations = await retriever.search(goal, subject, k)
    prepared = {chunk.id: chunk for chunk in chunks}
    selected: set[str] = set()
    if not citations:
        raise SourceError("Không tìm thấy đoạn nguồn phù hợp cho chủ đề.")
    for citation in citations:
        chunk = prepared.get(citation.chunk_id)
        if (
            chunk is None
            or citation.chunk_id in selected
            or (chunk.text, chunk.source_uri, chunk.page)
            != (citation.content, citation.source_uri, citation.page)
        ):
            raise SourceError("Trích dẫn không khớp nội dung nguồn đã lập chỉ mục.")
        selected.add(citation.chunk_id)
    return [chunk for chunk in chunks if chunk.id in selected]


def marked_chunks(chunks: Sequence[PreparedChunk]) -> str:
    """P4 can use this to keep exact chunk IDs in long-context graph extraction."""
    return "\n\n".join(
        f"[chunk_id={chunk.id}]\nsource_uri: {chunk.source_uri}\n"
        f"page: {chunk.page if chunk.page is not None else 'n/a'}\n{chunk.text}\n[/chunk]"
        for chunk in chunks
    )


class TopicPipeline:
    def __init__(
        self,
        ports: PipelinePorts,
        *,
        research_runner: Research = research,
        first_items: int = 6,
        quick_seconds: float = 60,
        deep_seconds: float = 480,
        retriever: ChunkRetriever,
        retrieval_subject: str,
        retrieval_k: int = 12,
    ) -> None:
        if first_items < 1 or not 0 < quick_seconds <= 60 or not 0 < deep_seconds <= 480:
            raise ValueError("Pipeline limits exceed the demo contract")
        self.ports, self.research = ports, research_runner
        self.first_items = first_items
        self.quick_seconds, self.deep_seconds = quick_seconds, deep_seconds
        if (
            retriever is None
            or not isinstance(retrieval_subject, str)
            or not 1 <= retrieval_k <= 50
        ):
            raise ValueError(
                "Retriever requires an explicit indexed subject and k between 1 and 50"
            )
        if not retrieval_subject.strip():
            raise ValueError("Retrieval subject must not be blank")
        self.retriever, self.retrieval_subject, self.retrieval_k = (
            retriever,
            retrieval_subject,
            retrieval_k,
        )

    async def run(
        self,
        request: TopicInput,
        on_progress: OnProgress,
        on_event: OnEvent,
    ) -> PipelineResult:
        # Revalidate even when the worker reconstructed a request with model_copy/construct.
        request = TopicInput.model_validate(request.model_dump())
        graph_ready = items_ready = False
        subject_slug: str | None = None
        dropped = 0
        stage = "research"
        summaries: tuple[SourceSummary, ...] = ()

        async def progress(status: Progress) -> None:
            await on_progress(replace(status, sources=summaries))

        async def trail(event: dict[str, str]) -> None:
            await on_event({**event, "at": datetime.now(UTC).isoformat()})

        try:
            async with asyncio.timeout(
                self.quick_seconds if request.mode == "quick" else self.deep_seconds
            ):
                upload: Document | None = None
                if request.upload_id:
                    upload = await self.ports.load_upload(request.upload_id)
                    if upload is None:
                        raise SourceError("Không tìm thấy tài liệu đã tải lên.")
                    if not upload.text_ok or not upload.source_uri:
                        raise SourceError("Tài liệu chưa có văn bản đọc được hoặc nguồn lưu trữ.")
                goal = request.goal_vi or (
                    "Chủ đề trong tài liệu: " + " ".join(page.text for page in upload.pages)[:1200]
                    if upload
                    else "Học theo tài liệu đã tải lên"
                )
                await progress(Progress("researching", "Đang chọn nguồn học…", 5))
                if request.mode == "deep":
                    await trail(
                        {
                            "kind": "search",
                            "text_vi": "Bắt đầu lượt research.",
                            "url": "",
                            "code": "research_started",
                            "outcome": "started",
                            "stage": "research",
                        }
                    )
                if request.mode == "deep":
                    sources = list(await self.research(goal, trail))
                    if len({s.url for s in sources}) < 3 or len({s.publisher for s in sources}) < 2:
                        raise SourceError("Nghiên cứu chưa đủ 3 nguồn từ 2 nhà xuất bản.")
                else:
                    # An upload is sufficient; Free mode never invokes web search.
                    sources = [] if upload else list(await self.ports.quick_sources(goal))
                if not sources and upload is None:
                    raise SourceError("Thư viện chưa có nguồn phù hợp; hãy tải tài liệu lên.")
                summaries = tuple(
                    SourceSummary(s.title, s.publisher, s.url, s.license) for s in sources
                )
                await progress(Progress("indexing", "Đang chuẩn bị nguồn trích dẫn…", 25))
                stage = "indexing"
                chunks = list(await self.ports.index(sources, upload))
                if not chunks or len({c.id for c in chunks}) != len(chunks):
                    raise SourceError("Chưa có đoạn nguồn hợp lệ để xây lộ trình.")
                chunks = await retrieve_chunks(
                    self.retriever, goal, self.retrieval_subject, chunks, self.retrieval_k
                )
                stage = "graph"
                graph = await self.ports.build_graph(goal, chunks, request.tier)
                if not graph.supported or not graph.graph:
                    raise SourceError("Sơ đồ kiến thức chưa được xác minh từ nguồn.")
                canonical_graph = KnowledgeGraph.model_validate(graph.graph)
                source_uris = {chunk.source_uri for chunk in chunks} | {
                    chunk.source_url for chunk in chunks if chunk.source_url
                }
                if any(
                    not set(concept.sources) <= source_uris for concept in canonical_graph.concepts
                ):
                    raise SourceError("Sơ đồ tham chiếu nguồn ngoài nội dung đã truy xuất.")
                await self.ports.save_graph(graph)
                subject_slug = graph.subject_slug
                await progress(
                    Progress(
                        "graph",
                        "Đang kiểm chứng câu hỏi cho bản đồ nháp.",
                        60,
                        False,
                        False,
                        subject_slug,
                    )
                )
                stage = "questions"
                generated = await self.ports.build_items(
                    graph, chunks, request.tier, self.first_items
                )
                chunk_ids = {chunk.id for chunk in chunks}
                verified: list[Item] = []
                seen: set[str] = set()
                for item in generated:
                    try:
                        ContractItem.model_validate(item.model_dump())
                        item = Item.model_validate(item.model_dump())
                    except ValidationError:
                        dropped += 1
                        continue
                    if (
                        item.status != "verified"
                        or not set(item.chunk_ids) <= chunk_ids
                        or item.source
                        not in {
                            uri
                            for chunk in chunks
                            if chunk.id in item.chunk_ids
                            for uri in (chunk.source_uri, chunk.source_url)
                            if uri
                        }
                        or item.id in seen
                    ):
                        dropped += 1
                        continue
                    seen.add(item.id)
                    verified.append(item)
                if len(verified) < self.first_items:
                    raise SourceError("Chưa đủ câu hỏi đã kiểm chứng để bắt đầu đánh giá.")
                await self.ports.save_items(subject_slug, verified)
                graph_ready = items_ready = True
                await progress(
                    Progress(
                        "items",
                        "Đã có câu hỏi đánh giá đầu vào.",
                        90,
                        True,
                        True,
                        subject_slug,
                        dropped,
                    )
                )
                await progress(
                    Progress(
                        "ready",
                        "Lộ trình đã sẵn sàng.",
                        100,
                        True,
                        True,
                        subject_slug,
                        dropped,
                    )
                )
                return PipelineResult(
                    subject_slug, tuple(i.id for i in verified), tuple(sources), dropped
                )
        except asyncio.CancelledError:
            # P2 owns cancellation/reclaim status. Do not turn worker shutdown into job failure.
            raise
        except Exception as exc:
            # Log locations and types, never provider responses, document text or credentials.
            logger.error(
                "research pipeline failed at %s (%s): %s",
                stage,
                type(exc).__name__,
                "; ".join(
                    f"{frame.name}:{frame.lineno}"
                    for frame in traceback.extract_tb(exc.__traceback__)
                ),
            )
            message = (
                "Đã hết thời gian xây lộ trình; hãy thử lại."
                if isinstance(exc, TimeoutError)
                else str(exc)
                if isinstance(exc, SourceError)
                else "Không thể hoàn tất bước sinh, kiểm chứng hoặc lưu câu hỏi lúc này."
                if stage == "questions"
                else "Không thể xây lộ trình lúc này."
            )
            try:
                async with asyncio.timeout(1):
                    await trail(
                        {
                            "kind": "read",
                            "text_vi": message,
                            "url": "",
                            "outcome": "failed",
                            "stage": stage,
                            "code": exc.code
                            if isinstance(exc, SourceError) and exc.code != "source_error"
                            else f"{stage}_failed",
                            "action_vi": exc.action_vi
                            if isinstance(exc, SourceError)
                            else "Kiểm tra cấu hình, hạn mức model và log backend theo mã job; "
                            "dữ liệu chưa được phát hành.",
                        }
                    )
            except Exception:
                pass
            try:
                async with asyncio.timeout(1):
                    await progress(
                        Progress(
                            "failed",
                            message,
                            0,
                            graph_ready,
                            items_ready,
                            subject_slug,
                            dropped,
                        )
                    )
            except Exception:
                # P2 must record the terminal state if its progress sink is unavailable.
                pass
            raise SourceError(message) from None
